/** Road names may be interstate, US, state, or local; never accept markup/control characters. */
export function validRoad(value) {
  return (
    typeof value === 'string' &&
    value === value.trim() &&
    value.length > 0 &&
    value.length <= 100 &&
    /^[\p{L}\p{N} .,'’()/#–—-]+$/u.test(value)
  );
}
